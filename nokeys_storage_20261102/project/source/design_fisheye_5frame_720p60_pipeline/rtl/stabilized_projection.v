 reg even_half,odd_half;
 reg [2:0] even_offset,odd_offset;
 wire selected_far=far_i===1'b1; // Preserve the original if(far_i) X behavior.
 wire [10:0] even_key={selected_far,even_address[10:1]};
 wire [10:0] odd_key={selected_far,odd_address[10:1]};
 function signed [15:0] slope_offset;
  input signed [12:0] slope;
  input [2:0] offset;
  reg signed [15:0] extended_slope;
  begin
   extended_slope={{3{slope[12]}},slope};
   slope_offset=(offset[0] ? extended_slope : 16'sd0)+
                (offset[1] ? extended_slope<<<1 : 16'sd0)+
                (offset[2] ? extended_slope<<<2 : 16'sd0);
  end
 endfunction
 function signed [7:0] difference_offset;
  input signed [4:0] slope;
  input [2:0] offset;
  reg signed [7:0] extended_slope;
  begin
   extended_slope={{3{slope[4]}},slope};
   difference_offset=(offset[0] ? extended_slope : 8'sd0)+
                     (offset[1] ? extended_slope<<<1 : 8'sd0)+
                     (offset[2] ? extended_slope<<<2 : 8'sd0);
  end
 endfunction
 function [43:0] exact_gain;
  input [52:0] base;
  input [12:0] residue;
  input [2:0] offset;
  reg signed [23:0] x,y;
  reg signed [15:0] difference;
  begin
   x=$signed({2'b0,base[21:0]})+
     slope_offset($signed(base[47:35]),offset)+$signed(residue[8:0]);
   difference=$signed(base[34:22])+
     difference_offset($signed(base[52:48]),offset)+$signed(residue[12:9]);
   y=x+difference;
   exact_gain={y[21:0],x[21:0]};
  end
 endfunction
 assign even_gain=exact_gain(even_base,even_half ? even_word[25:13] : even_word[12:0],even_offset);
 assign odd_gain=exact_gain(odd_base,odd_half ? odd_word[25:13] : odd_word[12:0],odd_offset);
 projection_residual_even packed_even(.clock(clock),.address(even_key),.word(packed_even_word));
 projection_residual_odd packed_odd(.clock(clock),.address(odd_key),.word(packed_odd_word));
 initial begin
  $readmemh("source/design_fisheye_5frame_720p60_pipeline/data/stabilization_reciprocal.mem",reciprocal);
  $readmemh("source/design_fisheye_5frame_720p60_pipeline/data/stabilization_lossless_base.mem",gain_base);


 end

 always @(posedge clock)begin
  seed<=reciprocal[reciprocal_address];

  even_base<=gain_base[{selected_far,even_address[10:2]}];
  odd_base<=gain_base[{selected_far,odd_address[10:2]}];
  even_half<=even_address[0];odd_half<=odd_address[0];
  even_offset<={even_address[1:0],1'b0};odd_offset<={odd_address[1:0],1'b1};
 end
endmodule

